-- ============================================================================
-- SCRIPT DE CRIAÇÃO DAS TABELAS E POLÍTICAS NO SUPABASE (SQL EDITOR)
-- ============================================================================

-- 1. Tabela de participantes do evento (equivalente à aba 'lista_evento')
CREATE TABLE IF NOT EXISTS public.lista_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    co_ies BIGINT NOT NULL,
    no_ies TEXT NOT NULL,
    no_pessoa_fisica TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índice para busca rápida por IES
CREATE INDEX IF NOT EXISTS idx_lista_evento_co_ies ON public.lista_evento(co_ies);

-- 2. Tabela de presenças (equivalente à aba 'presencas')
-- Possui UNIQUE em nome_participante para evitar duplicidade mesmo em acessos simultâneos!
CREATE TABLE IF NOT EXISTS public.presencas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_participante TEXT NOT NULL UNIQUE,
    nome_ies TEXT NOT NULL,
    presenca_dia1_manha TEXT DEFAULT '',
    presenca_dia1_tarde TEXT DEFAULT '',
    presenca_dia2_manha TEXT DEFAULT '',
    presenca_dia2_tarde TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabela de log/auditoria (opcional - equivalente à aba 'backup', registra cada batida de ponto)
CREATE TABLE IF NOT EXISTS public.historico_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_participante TEXT NOT NULL,
    nome_ies TEXT NOT NULL,
    turno TEXT NOT NULL,
    registrado_em TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- PERMISSÕES DE ACESSO (ROW LEVEL SECURITY - RLS)
-- Permite que o app Streamlit leia e registre presenças usando a chave pública
-- ============================================================================

ALTER TABLE public.lista_evento ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.presencas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historico_logs ENABLE ROW LEVEL SECURITY;

-- Políticas para lista_evento (apenas leitura pelo app)
DROP POLICY IF EXISTS "Permitir leitura publica de lista_evento" ON public.lista_evento;
CREATE POLICY "Permitir leitura publica de lista_evento"
ON public.lista_evento FOR SELECT
TO anon, authenticated
USING (true);

-- Políticas para presencas (leitura, inserção e atualização pelo app)
DROP POLICY IF EXISTS "Permitir leitura publica de presencas" ON public.presencas;
CREATE POLICY "Permitir leitura publica de presencas"
ON public.presencas FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "Permitir insercao publica em presencas" ON public.presencas;
CREATE POLICY "Permitir insercao publica em presencas"
ON public.presencas FOR INSERT
TO anon, authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir atualizacao publica em presencas" ON public.presencas;
CREATE POLICY "Permitir atualizacao publica em presencas"
ON public.presencas FOR UPDATE
TO anon, authenticated
USING (true)
WITH CHECK (true);

-- Políticas para historico_logs (inserção e leitura pelo app)
DROP POLICY IF EXISTS "Permitir insercao publica em historico_logs" ON public.historico_logs;
CREATE POLICY "Permitir insercao publica em historico_logs"
ON public.historico_logs FOR INSERT
TO anon, authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir leitura publica de historico_logs" ON public.historico_logs;
CREATE POLICY "Permitir leitura publica de historico_logs"
ON public.historico_logs FOR SELECT
TO anon, authenticated
USING (true);
